export function calculateGcs(eye: number, verbal: number, motor: number) {
  const total = eye + verbal + motor;
  let severity: 'severe' | 'moderate' | 'mild' = 'mild';
  if (total <= 8) {
    severity = 'severe'; // ໝົດສະຕິ/ວິກິດ
  } else if (total <= 12) {
    severity = 'moderate'; // ປານກາງ
  } else {
    severity = 'mild'; // ເລັກນ້ອຍ / ປົກກະຕິ
  }
  return { eye, verbal, motor, total, severity };
}

